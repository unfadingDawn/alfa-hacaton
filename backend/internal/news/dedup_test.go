package news

import "testing"

func TestSameEvent(t *testing.T) {
	cases := []struct {
		name string
		a, b string
		want bool
	}{
		// Одна новость из нескольких источников.
		{"ЦБ из разных изданий", "Банк России сохранил ключевую ставку на уровне 14% годовых",
			"ЦБ сохранил ключевую ставку на уровне 14%", true},
		{"Интерфакс и ТАСС", "ЦБ РФ сохранил ключевую ставку 14%", "Центробанк сохранил ключевую ставку на уровне 14,00%", true},
		{"Минфин", "Министерство финансов разместило ОФЗ на 50 млрд рублей", "Минфин разместил ОФЗ на 50 млрд руб.", true},
		// Разный регистр и написание названий.
		{"регистр", "ГАЗПРОМ увеличил добычу газа в сентябре", "Газпром увеличил добычу газа в сентябре", true},
		{"ё и пунктуация", "«Сбер» снизил ставки по вкладам — ещё раз", "Сбер снизил ставки по вкладам, еще раз", true},
		// Похожие, но разные события.
		{"направление ставки", "ЦБ сохранил ключевую ставку на уровне 14%", "ЦБ повысил ключевую ставку до 15%", false},
		{"разные суммы", "Минфин разместил ОФЗ на 50 млрд рублей", "Минфин разместил ОФЗ на 30 млрд рублей", false},
		{"разные банки", "Сбербанк повысил ставки по вкладам", "ВТБ повысил ставки по вкладам", false},
		{"повысил и снизил", "Сбербанк повысил ставки по вкладам", "Сбербанк снизил ставки по вкладам", false},
		{"другая тема", "ЦБ сохранил ключевую ставку на уровне 14%", "ЦБ отозвал лицензию у банка «Восход»", false},
		{"короткие заголовки", "Рынок вырос", "Рынок упал", false},
	}
	for _, c := range cases {
		if got := SameEvent(c.a, c.b); got != c.want {
			t.Errorf("%s: SameEvent(%q, %q) = %v, ожидалось %v", c.name, c.a, c.b, got, c.want)
		}
		if got := SameEvent(c.b, c.a); got != c.want {
			t.Errorf("%s: функция должна быть симметричной", c.name)
		}
	}
}
