func Get(code string) (Role, bool) {
	for _, r := range All {
		if r.Code == code {
			return r, true
		}
	}
	return Role{}, false
}

// Resolve возвращает роль или общую линзу, если роль не выбрана.
func Resolve(code string) Role {
	if r, ok := Get(code); ok {
		return r
	}
	r, _ := Get("other")
	return r
}
